#!/usr/bin/env node
// Mint the MusicKit developer token and write it into app/src/main/assets/config.js.
//
//   node tools/make-token.mjs --key ~/.config/nocturnify-am/AuthKey_XXXXXXXXXX.p8 --team TEAMID [--days 180]
//
// The token is an ES256 JWT signed with your Media Services key. Apple caps its lifetime at
// 6 months, so re-run this (and rebuild) before it lapses; the app says so on screen when it
// has. The .p8 never leaves this Mac — only the signed token goes into the (gitignored) config.
import { readFileSync, writeFileSync } from 'node:fs';
import { sign } from 'node:crypto';
import { homedir } from 'node:os';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = Object.fromEntries(process.argv.slice(2).reduce((a, v, i, all) =>
  (v.startsWith('--') ? a.concat([[v.slice(2), all[i + 1]]]) : a), []));
const keyPath = (args.key || '').replace(/^~/, homedir());
const team = args.team;
const days = Math.min(180, Number(args.days || 180));
if (!keyPath || !team) {
  console.error('usage: node tools/make-token.mjs --key path/to/AuthKey_KEYID.p8 --team TEAMID [--days 180]');
  process.exit(1);
}
const kid = args.kid || (basename(keyPath).match(/AuthKey_([A-Z0-9]+)\.p8$/) || [])[1];
if (!kid) { console.error('cannot read the key id from the file name; pass --kid'); process.exit(1); }

const b64url = b => Buffer.from(b).toString('base64').replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
const now = Math.floor(Date.now() / 1000);
const exp = now + days * 86400;
const input = `${b64url(JSON.stringify({ alg: 'ES256', kid }))}.${b64url(JSON.stringify({ iss: team, iat: now, exp }))}`;
const sig = sign('sha256', Buffer.from(input), { key: readFileSync(keyPath), dsaEncoding: 'ieee-p1363' });
const token = `${input}.${b64url(sig)}`;

const out = join(dirname(fileURLToPath(import.meta.url)), '../app/src/main/assets/config.js');
const expires = new Date(exp * 1000).toISOString().slice(0, 10);
writeFileSync(out, `// Generated by tools/make-token.mjs — do not commit. Expires ${expires}.
window.CONFIG = {
  developerToken: '${token}',
  tokenExpires: '${expires}',
  appName: 'Nocturnify',
};
`);
console.log(`wrote ${out} (key ${kid}, team ${team}, expires ${expires})`);
